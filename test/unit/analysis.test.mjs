import { describe, it } from 'node:test';
import { parseJestJson, parseTestScript, parseTextCounts, summariseFileCoverage } from '../../skill/scripts/lib/coverage.mjs';
import { addDevCommand, detectProject, detectRunner } from '../../skill/scripts/lib/detect.mjs';
import { discoverFiles, globToRegExp, isTestFile, mapTestsToSources } from '../../skill/scripts/lib/files.mjs';
