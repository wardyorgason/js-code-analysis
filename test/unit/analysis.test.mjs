function tmpProject(files) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'jsca-unit-'));
  for (const [name, content] of Object.entries(files)) {
    const p = path.join(root, name);
    fs.mkdirSync(path.dirname(p), { recursive: true });
    fs.writeFileSync(p, typeof content === 'string' ? content : JSON.stringify(content));
  }
  return fs.realpathSync(root);
}

describe('util', () => {
  it('collapses line numbers into ranges', () => {
    assert.equal(lineRanges([7, 3, 4, 5, 12, 20, 21]), '3-5, 7, 12, 20-21');
    assert.equal(lineRanges([1, 3, 5], 2), '1, 3, … 1 more');
  });
  it('returns null percentage for empty totals', () => {
    assert.equal(pct(0, 0), null);
    assert.equal(pct(1, 4), 25);
  });
});

describe('files', () => {
  it('matches FTA-style globs against file names', () => {
    assert.ok(globToRegExp('*.test.ts').test('foo.test.ts'));
    assert.ok(!globToRegExp('*.test.ts').test('foo.ts'));
    assert.ok(globToRegExp('.d.ts').test('types.d.ts'));
  });
  it('recognises test files by name and directory', () => {
    assert.ok(isTestFile('src/a.spec.tsx'));
    assert.ok(isTestFile('src/__tests__/a.ts'));
    assert.ok(isTestFile('test/helpers.js'));
    assert.ok(!isTestFile('src/testing-library-wrapper.ts'));
  });
  it('separates sources from tests, config and generated files', () => {
    const root = tmpProject({
      'src/a.ts': 'export const a = 1;',
      'src/a.test.ts': "import { a } from './a';",
      'src/types.d.ts': 'declare const x: number;',
      'src/gen.ts': '// @generated by tool\nexport {}',
      'src/vite.config.ts': 'export default {}',
      'src/lib/index.ts': 'export {}',
      'node_modules/x/index.js': '',
      'scripts/build.js': '',
    });
    const { sources, tests } = discoverFiles({ projectRoot: root, sourceRoots: [path.join(root, 'src')] });
    assert.deepEqual(sources.map((s) => path.relative(root, s)), ['src/a.ts', 'src/lib/index.ts']);
    assert.deepEqual(tests.map((s) => path.relative(root, s)), ['src/a.test.ts']);
  });
  it('maps tests to sources by import path and by name', () => {
    const root = tmpProject({
      'src/a.ts': '',
      'src/b.ts': '',
      'src/widget/index.ts': '',
      'test/uses-a.test.ts': "import { a } from '../src/a.js';\nvi.mock('../src/b')",
      'test/widget.test.ts': '',
    });
    const sources = ['src/a.ts', 'src/b.ts', 'src/widget/index.ts'].map((f) => path.join(root, f));
    const tests = ['test/uses-a.test.ts', 'test/widget.test.ts'].map((f) => path.join(root, f));
    const map = mapTestsToSources(sources, tests);
    assert.equal(map.get(sources[0]).size, 1);
    assert.equal(map.get(sources[1]).size, 1);
    assert.equal(map.get(sources[2]).size, 1);
  });
});

describe('detect', () => {
  it('detects the runner from the test script before dependencies', () => {
    assert.equal(detectRunner('/nope', { scripts: { test: 'vitest run' }, devDependencies: { jest: '1' } }).runner, 'vitest');
    assert.equal(detectRunner('/nope', { scripts: { test: 'node --test src/' } }).runner, 'node-test');
    assert.equal(detectRunner('/nope', { scripts: { test: 'react-scripts test' } }).runner, 'jest');
    assert.equal(detectRunner('/nope', { scripts: { test: 'echo "Error: no test specified" && exit 1' } }).runner, 'none');
    assert.equal(detectRunner('/nope', { scripts: { test: 'npm run unit' } }).runner, 'other');
    assert.equal(detectRunner('/nope', { devDependencies: { mocha: '1' } }).runner, 'mocha');
  });
  it('builds install commands per package manager', () => {
    assert.equal(addDevCommand('npm', 'c8'), 'npm install --save-dev c8');
    assert.equal(addDevCommand('pnpm', 'c8', { workspaceRoot: true }), 'pnpm add -D -w c8');
    assert.equal(addDevCommand('bun', 'c8'), 'bun add -d c8');
  });
  it('asks to install a vitest coverage provider pinned to the installed vitest', () => {
    const root = tmpProject({
      'package.json': { scripts: { test: 'vitest' }, devDependencies: { vitest: '^5.0.0' } },
      'package-lock.json': '{}',
      'node_modules/vitest/package.json': { name: 'vitest', version: '5.0.2' },
    });
    const d = detectProject(root);
    assert.deepEqual(d.actions.map((a) => a.command), ['npm install --save-dev @vitest/coverage-v8@5.0.2']);
  });
  it('needs no install for jest or for runners covered by the bundled c8', () => {
    const jest = tmpProject({ 'package.json': { scripts: { test: 'jest' }, devDependencies: { jest: '1' } }, 'node_modules/jest/package.json': {} });
    assert.deepEqual(detectProject(jest).actions, []);
    const node = tmpProject({ 'package.json': { scripts: { test: 'node --test' } } });
    assert.deepEqual(detectProject(node).actions, []);
    assert.equal(detectProject(node).coverage.tool, 'c8 (bundled)');
  });
  it('asks for a dependency install when node_modules is missing', () => {
    const root = tmpProject({ 'package.json': { scripts: { test: 'jest' }, devDependencies: { jest: '1' } }, 'yarn.lock': '' });
    assert.deepEqual(detectProject(root).actions.map((a) => a.command), ['yarn install']);
  });
});

describe('coverage', () => {
  it('parses simple test scripts and rejects chains', () => {
    assert.deepEqual(parseTestScript('NODE_OPTIONS=--experimental-vm-modules jest --runInBand', 'jest'), {
      env: ['NODE_OPTIONS=--experimental-vm-modules'], args: ['--runInBand'],
    });
    assert.deepEqual(parseTestScript('cross-env TZ=UTC vitest run', 'vitest'), { env: ['TZ=UTC'], args: ['run'] });
    assert.equal(parseTestScript('tsc && vitest', 'vitest'), null);
    assert.equal(parseTestScript('mocha', 'jest'), null);
  });
  it('reads counts from mocha and node:test output', () => {
    assert.deepEqual(parseTextCounts('  5 passing (20ms)\n  2 failing\n  1 pending'), { total: 8, passed: 5, failed: 2, skipped: 1, suites: null, failedSuites: null });
    assert.equal(parseTextCounts('ℹ tests 3\nℹ pass 3\nℹ fail 0').passed, 3);
    assert.equal(parseTextCounts('nothing here'), null);
  });
  it('reads jest-format JSON including suites that failed to load', () => {
    const root = tmpProject({
      'r.json': {
        numTotalTests: 2, numPassedTests: 1, numFailedTests: 1, numPendingTests: 0, numTodoTests: 0, numTotalTestSuites: 2, numFailedTestSuites: 2,
        testResults: [
          { name: '/a.test.js', status: 'failed', assertionResults: [{ status: 'failed', fullName: 'a works', failureMessages: ['boom'] }] },
          { name: '/b.test.js', status: 'failed', message: 'SyntaxError', assertionResults: [] },
        ],
      },
    });
    const r = parseJestJson(path.join(root, 'r.json'));
    assert.equal(r.counts.failed, 1);
    assert.equal(r.failures[0].name, 'a works');
    assert.equal(r.suiteErrors[0].file, '/b.test.js');
  });
  it('assigns statements and branches to the innermost function', () => {
    const loc = (a, b) => ({ start: { line: a, column: 0 }, end: { line: b, column: 99 } });
    const fc = {
      statementMap: { 0: loc(2, 2), 1: loc(3, 3), 2: loc(6, 6) },
      s: { 0: 1, 1: 0, 2: 0 },
      fnMap: { 0: { name: 'outer', decl: loc(1, 1), loc: loc(1, 8) }, 1: { name: 'inner', decl: loc(5, 5), loc: loc(5, 7) } },
      f: { 0: 1, 1: 0 },
      branchMap: {
        0: { type: 'if', loc: loc(3, 3), locations: [loc(3, 3), loc(3, 3)] },
        1: { type: 'if', loc: loc(6, 6), locations: [loc(6, 6), loc(6, 6)] },
        2: { type: 'switch', loc: loc(6, 6), locations: [loc(6, 6), loc(6, 6), loc(6, 6)] },
      },
      b: { 0: [1, 0], 1: [0, 0], 2: [0, 0, 0] },
    };
    const s = summariseFileCoverage(fc);
    assert.deepEqual(s.lines, { total: 3, covered: 1 });
    assert.deepEqual(s.branches, { total: 7, covered: 1 });
    const [outer, inner] = s.functions.list;
    assert.equal(outer.complexity, 2);
    assert.equal(inner.complexity, 4);
    assert.deepEqual(inner.statements, { total: 1, covered: 0 });
    assert.deepEqual(s.uncoveredLines, [3, 6]);
  });
});

describe('findings', () => {
  const base = { projectRoot: '/p', testMap: new Map() };
  const fta = (score, cyclo, lineCount = 100) => ({ score, cyclo, lineCount, assessment: 'x' });

  it('flags complex files without coverage as Critical', () => {
    const [r] = analyseFiles({ ...base, sources: ['/p/a.js'], fta: new Map([['/p/a.js', fta(65, 30)]]), coverageByFile: new Map(), coverageMode: 'measured' });
    assert.equal(r.covState, 'not-loaded');
    assert.equal(r.severity, 'Critical');
    assert.ok(r.findings.some((f) => f.code === 'ComplexAndUntested'));
    assert.ok(!r.findings.some((f) => f.code === 'NoCoverage'));
  });
  it('treats high scores with few branches as data-heavy, not a hotspot', () => {
    const [r] = analyseFiles({ ...base, sources: ['/p/a.js'], fta: new Map([['/p/a.js', fta(62, 3)]]), coverageByFile: null, coverageMode: 'skipped' });
    assert.deepEqual(r.findings.map((f) => f.code), ['DataHeavy']);
    assert.equal(rankHotspots([r], []).length, 0);
  });
  it('reports every file as untested when the project has no tests', () => {
    const [r] = analyseFiles({ ...base, sources: ['/p/a.js'], fta: new Map([['/p/a.js', fta(30, 8)]]), coverageByFile: null, coverageMode: 'none' });
    assert.equal(r.findings[0].code, 'NoCoverage');
    assert.equal(r.findings[0].severity, 'High');
  });
  it('ranks project findings first, then by severity and risk', () => {
    const files = analyseFiles({
      ...base,
      sources: ['/p/a.js', '/p/b.js'],
      fta: new Map([['/p/a.js', fta(30, 6)], ['/p/b.js', fta(30, 12)]]),
      coverageByFile: null,
      coverageMode: 'none',
    });
    const pf = projectFindings({ detection: { runner: { runner: 'none', reason: 'x' } }, testRun: null, coverageMode: 'none', sourcesCount: 2, testsCount: 0 });
    const ranked = rankHotspots(files, pf);
    assert.deepEqual(ranked.map((h) => h.target), ['(project)', 'b.js', 'a.js']);
  });
  it('computes CRAP-style risk', () => {
    assert.equal(crap(10, 1), 10);
    assert.equal(crap(10, 0), 110);
  });
});

describe('fta', () => {
  it('only adds to FTA list settings and never fails on score', () => {
    const cfg = buildFtaConfig({ exclude_directories: ['generated'] });
    assert.ok(cfg.exclude_directories.includes('generated'));
    assert.ok(cfg.exclude_directories.includes('__tests__'));
    assert.ok(cfg.extensions.includes('.mjs'));
    assert.equal(cfg.score_cap, 100000);
  });
  it('extracts the JSON array from noisy output', () => {
    assert.deepEqual(extractJsonArray('warn: x\n[{"a":1}]\n'), [{ a: 1 }]);
    assert.equal(extractJsonArray('no json'), null);
  });
});
